/**
 * End-to-end content smoke test against the real database.
 *
 *   node --env-file=.env scripts/test-cms.mjs          -> create + verify
 *   node --env-file=.env scripts/test-cms.mjs --clean   -> delete test records
 *
 * Creates clearly-labelled TEST records, exercises published-only queries and
 * removes them again. Nothing is left behind.
 */
import { getPayload } from 'payload'

import config from '../payload.config.js'

const clean = process.argv.includes('--clean')
const payload = await getPayload({ config })

const TAG = 'ZZ Test'

async function findTest(collection) {
  const { docs } = await payload.find({
    collection,
    where: { title: { contains: TAG } },
    limit: 100,
    depth: 0,
    overrideAccess: true,
  })
  return docs
}

async function removeTest(collection) {
  const docs = await findTest(collection)
  for (const doc of docs) {
    await payload.delete({ collection, id: doc.id, overrideAccess: true })
  }
  console.log(`${collection}: removed ${docs.length}`)
}

if (clean) {
  // Posts reference categories, so remove posts first.
  await removeTest('posts')
  await removeTest('projects')
  await removeTest('pages')
  await removeTest('categories')
  const testimonials = await payload.find({
    collection: 'testimonials',
    where: { name: { contains: TAG } },
    limit: 100,
    depth: 0,
    overrideAccess: true,
  })
  for (const doc of testimonials.docs) {
    await payload.delete({ collection: 'testimonials', id: doc.id, overrideAccess: true })
  }
  console.log(`testimonials: removed ${testimonials.docs.length}`)
  await removeTestUsers()
  process.exit(0)
}

async function removeTestUsers() {
  const users = await payload.find({
    collection: 'users',
    where: { email: { contains: 'zz-test-' } },
    limit: 100,
    depth: 0,
    overrideAccess: true,
  })
  for (const user of users.docs) {
    await payload.delete({ collection: 'users', id: user.id, overrideAccess: true })
  }
  console.log(`test users: removed ${users.docs.length}`)
}

