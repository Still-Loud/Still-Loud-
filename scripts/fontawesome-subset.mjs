/**
 * Build a minimal Font Awesome CSS from the full 6.4.0 build.
 *
 * The site uses 27 icons out of ~2,000. shipping all.min.css (100 KB) plus the
 * fa-brands/fa-regular webfonts is the single largest render-blocking request
 * after the app CSS. This script keeps only the rules whose selectors name a
 * class that actually appears in components/, app/ or styles/, plus the
 * @font-face blocks and base classes they depend on.
 *
 *   node scripts/fontawesome-subset.mjs
 */
import fs from 'node:fs/promises'
import path from 'node:path'

const SRC = 'scripts/fontawesome/all.min.css'
/* Emitted into styles/ so Next bundles it with the rest of the site CSS and
   the browser makes ONE render-blocking CSS request instead of two. The
   webfonts stay in public/ and are referenced with absolute paths. */
const OUT = 'styles/fontawesome.css'

/** Classes that are structural, not icons — always keep. */
const KEEP = new Set([
  'fa',
  'fas',
  'far',
  'fab',
  'fa-solid',
  'fa-regular',
  'fa-brands',
  'fa-classic',
  'fa-sharp',
  'fa-fw',
  'fa-spin',
  'fa-pulse',
  'fa-beat',
  'fa-fade',
  'fa-bounce',
  'fa-shake',
  'fa-flip',
  'sr-only',
  'fa-sr-only',
])

async function usedClasses() {
  const found = new Set()
  const dirs = ['components', 'app', 'styles']

  async function walk(dir) {
    let entries
    try {
      entries = await fs.readdir(dir, { withFileTypes: true })
    } catch {
      return
    }
    for (const entry of entries) {
      const p = path.join(dir, entry.name)
      if (entry.isDirectory()) await walk(p)
      else if (p.replace(/\\/g, '/') === OUT) continue // don't scan our own output
      else if (/\.(js|jsx|mjs|css)$/.test(entry.name)) {
        const text = await fs.readFile(p, 'utf8')
        for (const m of text.matchAll(/\bfa-[a-z0-9-]+/g)) found.add(m[0])
      }
    }
  }

  for (const dir of dirs) await walk(dir)
  return found
}

/** Split a stylesheet into top-level blocks, honouring nested braces. */
function blocks(css) {
  const out = []
  let start = 0
  let depth = 0

  for (let i = 0; i < css.length; i += 1) {
    const ch = css[i]
    if (ch === '{') depth += 1
    else if (ch === '}') {
      depth -= 1
      if (depth === 0) {
        out.push(css.slice(start, i + 1).trim())
        start = i + 1
      }
    }
  }

  return out.filter(Boolean)
}

/** Every `.class` name in a rule's selector list. */
function selectors(block) {
  const brace = block.indexOf('{')
  const selector = brace === -1 ? block : block.slice(0, brace)
  return [...selector.matchAll(/\.([a-z0-9-]+)/g)].map((m) => m[1])
}

const used = await usedClasses()
const css = await fs.readFile(SRC, 'utf8')

const kept = []
const keptIcons = new Set()

for (const block of blocks(css)) {
  if (block.startsWith('@font-face') || block.startsWith('@keyframes')) {
    kept.push(block)
    continue
  }
  if (block.startsWith(':root') || block.startsWith(':host')) {
    kept.push(block)
    continue
  }

  const names = selectors(block)
  if (names.length === 0) continue

  const hit = names.filter((n) => KEEP.has(n) || used.has(n))
  if (hit.length === 0) continue

  for (const n of hit) if (!KEEP.has(n)) keptIcons.add(n)
  kept.push(block)
}

const missing = [...used].filter((n) => !KEEP.has(n) && !keptIcons.has(n))

const output = `/* Font Awesome Free 6.4.0 — subset generated by scripts/fontawesome-subset.mjs.\n   Do not edit by hand; re-run the script after adding a new icon to a component. */\n${kept
  .join('')
  .replace(/url\(\.\.\/webfonts\//g, 'url(/vendor/fontawesome/webfonts/')}\n`

await fs.writeFile(OUT, output)

const before = (await fs.stat(SRC)).size
const after = (await fs.stat(OUT)).size

console.log(`${kept.length} blocks kept`)
console.log(`${keptIcons.size} icon classes: ${[...keptIcons].sort().join(' ')}`)
console.log(`missing (referenced but not in 6.4.0): ${missing.join(' ') || 'none'}`)
console.log(`${Math.round(before / 1024)} KB -> ${Math.round(after / 1024)} KB`)
